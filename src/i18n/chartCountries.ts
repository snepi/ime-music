const NAMES: Record<LocaleCode, NameTable> = { ru, en, uk, es, fr, zh, hi };

export function chartCountryLabel(locale: LocaleCode, code: string): string {
  const table = NAMES[locale] || NAMES.ru;
  return table[code as ChartCountryCode] || NAMES.en[code as ChartCountryCode] || code;
}

/** World first, then A→Z in the active UI language */
export function chartCountryOptions(locale: LocaleCode): { value: string; label: string }[] {
  const bcp = localeBcp47(locale);
  const rest = CHART_COUNTRY_CODES.filter((c) => c !== 'world')
    .map((code) => ({ value: code, label: chartCountryLabel(locale, code) }))
    .sort((a, b) => a.label.localeCompare(b.label, bcp, { sensitivity: 'base' }));
  return [{ value: 'world', label: chartCountryLabel(locale, 'world') }, ...rest];
}
